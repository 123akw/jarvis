_BY_ID = {scene["id"]: scene for scene in SCENES}


def scene_by_id(scene_id: str):
    return _BY_ID.get(str(scene_id or ""))


def scene_prompt(scene_id: str) -> str:
    scene = scene_by_id(scene_id) or _BY_ID["butler"]
    return scene["prompt"]


def catalog() -> list[dict]:
    """给前端的场景清单（不含提示词正文，防提示词被当成 UI 文案）。"""
    return [{"id": s["id"], "name": s["name"], "icon": s.get("icon", ""),
             "opening": s.get("opening", "")} for s in SCENES]
